#!/usr/bin/env python3
"""
K-means clustering for LSAT-LR training subset selection.

Embeds each training sample (passage + question) using a lightweight
sentence-transformer, then picks the K nearest-to-centroid samples
as representative training examples.

Usage:
    python -m eval.lsat_lr.cluster_train --clusters 20
    python -m eval.lsat_lr.cluster_train --clusters 10 15 20 30
"""

from __future__ import annotations

import argparse
import json
import os
from typing import Dict, List

import numpy as np

TRAIN_PATH  = "./eval/lsat_lr/data/lsat_lr_train.jsonl"
OUTPUT_DIR  = "./eval/lsat_lr/data"
CONFIG_PATH = "./eval/lsat_lr/data/sample_config.json"
EMBED_PATH  = "./eval/lsat_lr/data/embeddings.npy"

DEFAULT_CLUSTERS = [20]


# ── helpers ──────────────────────────────────────────────────────────────────

def load_jsonl(path: str) -> List[Dict]:
    data = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                data.append(json.loads(line))
    return data


def save_jsonl(data: List[Dict], path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        for item in data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")
    print(f"    Saved {len(data)} samples → {path}")


# ── embedding ────────────────────────────────────────────────────────────────

def get_embeddings(samples: List[Dict]) -> np.ndarray:
    """Load pre-computed embeddings.npy (generated by embed_train.py)."""
    if not os.path.exists(EMBED_PATH):
        raise FileNotFoundError(
            f"Embeddings not found: {EMBED_PATH}\n"
            "Run first:  python -m eval.lsat_lr.embed_train"
        )
    X = np.load(EMBED_PATH)
    if X.shape[0] != len(samples):
        raise ValueError(
            f"Embedding rows ({X.shape[0]}) != samples ({len(samples)}). "
            "Re-run embed_train.py."
        )
    print(f"  Loaded embeddings {X.shape} from {EMBED_PATH}")
    return X


# ── clustering ───────────────────────────────────────────────────────────────

def kmeans_select(samples: List[Dict], X: np.ndarray, k: int) -> List[Dict]:
    """Run K-means and pick the sample closest to each centroid."""
    from sklearn.cluster import KMeans

    print(f"  K-means k={k} on {X.shape} ...")
    km = KMeans(n_clusters=k, random_state=42, n_init=20, max_iter=500)
    km.fit(X)

    selected: List[Dict] = []
    for c_idx in range(k):
        mask   = km.labels_ == c_idx
        idxs   = np.where(mask)[0]
        center = km.cluster_centers_[c_idx]
        dists  = np.linalg.norm(X[idxs] - center, axis=1)
        chosen = idxs[np.argmin(dists)]
        selected.append(samples[chosen])

    return selected


# ── config ───────────────────────────────────────────────────────────────────

def update_config(new_tasks: Dict[str, Dict]) -> None:
    if os.path.exists(CONFIG_PATH):
        with open(CONFIG_PATH, encoding="utf-8") as f:
            cfg = json.load(f)
    else:
        cfg = {}

    cfg.update(new_tasks)
    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=4)
    print(f"  Updated config → {CONFIG_PATH}")
    print(f"  Available tasks: {sorted(cfg.keys())}")


# ── main ─────────────────────────────────────────────────────────────────────

def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--clusters", nargs="+", type=int, default=DEFAULT_CLUSTERS)
    args = ap.parse_args()

    print("=" * 60)
    print("LSAT-LR — K-means Cluster Subset Selection")
    print("=" * 60)

    samples = load_jsonl(TRAIN_PATH)
    print(f"\nLoaded {len(samples)} training samples from {TRAIN_PATH}")

    X = get_embeddings(samples)

    new_tasks: Dict[str, Dict] = {}

    for k in sorted(args.clusters):
        print(f"\n── K={k} ──")
        subset = kmeans_select(samples, X, k)

        out_path  = os.path.join(OUTPUT_DIR, f"lsat_lr_train_cluster{k}.jsonl")
        task_name = f"lsat_lr_cluster{k}"

        save_jsonl(subset, out_path)

        new_tasks[task_name] = {
            "train_data": out_path,
            "val_data":   "./eval/lsat_lr/data/lsat_lr_val.jsonl",
            "test_data":  "./eval/lsat_lr/data/lsat_lr_test.jsonl",
        }
        print(f"  Task: {task_name}")

    update_config(new_tasks)
    print(f"\n{'=' * 60}\nDone.\n{'=' * 60}")


if __name__ == "__main__":
    main()
